"""Install an exported registry-operator solution into a hardware kernel profile.

``python -m scripts.kernel_tuning install EXPORT --profile NAME`` runs in the model
runtime on the target machine. It copies the winning sources of a registry task
(see :mod:`scripts.kernel_tuning.regions`) into
``embodiinfer/backend/triton/tuned/NAME/<op>/`` and records the operator in that
profile's ``profile.json``, matched to the current device and Torch/Triton
versions. The generated package only applies to argument layouts the evaluator
verified (every recorded workload); other calls fall back to the policy's
preferred implementation. Installing changes no default: select the profile
with ``kernel_profile``.
"""

from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path
from typing import Any

from .contracts import ContractError, TaskPackage, read_json, relative_path

_MATCH = ("device_name", "capability", "torch", "triton")
PROFILE_ROOT = Path(__file__).resolve().parents[2] / "embodiinfer" / "backend" / "triton" / "tuned"
_PACKAGE = '''"""Tuned ``{op}`` kernel for the ``{profile}`` profile.

Generated by ``scripts.kernel_tuning install`` from run {run_id}; do not edit,
reinstall instead. The kernel applies only to the argument layouts verified by
the evaluator. Strides of size-one dimensions and of empty tensors address no
other element, so they are compared as zero. Like the evaluator, the kernel
receives only the tensor arguments; constants are part of the verified layout.
"""

import torch

from .{module} import {symbol} as run

_VERIFIED = frozenset({cases})
_ARGUMENTS = {arguments}
_TENSORS = {tensors}


def _strides(shape, stride):
    if 0 in shape:
        return (0,) * len(shape)
    return tuple(0 if size == 1 else step for size, step in zip(shape, stride))


def _leaves(value, out):
    if isinstance(value, torch.Tensor):
        dtype = str(value.dtype).removeprefix("torch.")
        shape = tuple(value.shape)
        out.append(("tensor", shape, _strides(shape, value.stride()), dtype))
    elif isinstance(value, (tuple, list)):
        for item in value:
            _leaves(item, out)
    elif isinstance(value, dict):
        for key in sorted(value):
            _leaves(value[key], out)
    else:
        out.append(("constant", repr(value)))
    return out


def applies(*args, **kwargs):
    """Whether these arguments match a layout the evaluator verified."""
    return tuple(_leaves((args, kwargs), [])) in _VERIFIED


def _bind(recipe, value, tensors):
    kind, item = next(iter(recipe.items()))
    if kind == "tensor":
        tensors[item] = value
    elif kind in ("tuple", "list"):
        for entry, element in zip(item, value):
            _bind(entry, element, tensors)
    elif kind == "dict":
        for key, entry in item.items():
            _bind(entry, value[key], tensors)


def call(*args, **kwargs):
    """Call the kernel as the evaluator did: with the captured tensor arguments x0..xN."""
    tensors = {{}}
    _bind(_ARGUMENTS, (args, kwargs), tensors)
    return run(*(tensors[index] for index in range(_TENSORS)))
'''


def canonical_strides(shape: tuple[int, ...], stride: tuple[int, ...]) -> tuple[int, ...]:
    """Strides with those that address no other element (size-one or empty tensors) as zero.

    Eager and compiled runs of the same model can differ only there, e.g. a
    ``(1, 1, L, D)`` cache with stride ``(L*D, L*D, D, 1)`` or ``(L*D, D, D, 1)``.
    Mirrors ``_strides`` in the generated package.
    """
    if 0 in shape:
        return (0,) * len(shape)
    return tuple(0 if size == 1 else step for size, step in zip(shape, stride))


def recorded_signature(recipe: dict[str, Any], inputs: list[dict[str, Any]]) -> tuple[Any, ...]:
    """Leaf signature of a captured call, matching the generated ``applies`` traversal."""
    leaves: list[tuple[Any, ...]] = []

    def walk(node: dict[str, Any]) -> None:
        kind, value = next(iter(node.items()))
        if kind == "tensor":
            spec = inputs[value]
            shape = tuple(spec["shape"])
            leaves.append(("tensor", shape, canonical_strides(shape, tuple(spec["stride"])), spec["dtype"]))
        elif kind in ("tuple", "list"):
            for item in value:
                walk(item)
        elif kind == "dict":
            for key in sorted(value):
                walk(value[key])
        elif kind == "constant":
            leaves.append(("constant", repr(value)))
        else:
            raise ContractError(f"Registry kernels cannot gate arguments of kind {kind}")

    walk(recipe)
    return tuple(leaves)


def install(
    export: Path, profile: str, *, root: Path = PROFILE_ROOT, replace: bool = False
) -> dict[str, Any]:
    """Copy one exported registry solution into ``root/profile`` and update its manifest."""
    from embodiinfer.backend.triton.tuned import current_environment, load_profile, source_digest
    from embodiinfer.layers.ops import available_ops

    if not profile.isidentifier():
        raise ContractError("Profile names must be Python identifiers, e.g. thor or rtx4090")
    export = export.resolve()
    task = TaskPackage.load(export / "task")
    generated = read_json(task.root / "generated.json")
    op = generated.get("registry_op")
    if generated.get("generator") != "scripts.kernel_tuning.regions" or not op:
        raise ContractError("Only registry-operator tasks (capture-ops) can be installed")
    if op not in available_ops():
        raise ContractError(f"{op!r} is not registered in this source tree; merge its registration first")
    solution = read_json(export / "solution.json")
    spec = solution["spec"]
    if spec.get("language") != "triton":
        raise ContractError("Only Python/Triton solutions can be installed into a kernel profile")
    entry_file, symbol = spec["entry_point"].split("::")
    module = Path(relative_path(entry_file)).with_suffix("").as_posix().replace("/", ".")
    replay = read_json(task.root / "replay.json")
    identity = replay.get("numerical_identity") or {}
    if identity.get("op") != op:
        raise ContractError("Task replay identity does not match its registry operator")
    environment = current_environment()
    if replay["torch_version"] != environment["torch"]:
        raise ContractError("The task was captured with another Torch version; tune on this runtime")
    cases = sorted(
        {recorded_signature(identity["arguments"], case["inputs"]) for case in replay["cases"].values()}
    )
    run = read_json(export / "manifest.json")
    attempt = next(item for item in run["attempts"] if item["id"] == run["best"])
    directory = root / profile
    manifest_path = directory / "profile.json"
    manifest = (
        read_json(manifest_path)
        if manifest_path.is_file()
        else {"schema": 1, "match": {key: environment.get(key) for key in _MATCH}, "ops": {}}
    )
    if any(manifest["match"].get(key) != environment.get(key) for key in _MATCH):
        raise ContractError(f"Profile {profile!r} was verified for {manifest['match']}, not {environment}")
    if op in manifest["ops"] and not replace:
        raise ContractError(f"{profile}/{op} is already installed; pass --replace to overwrite it")
    directory.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{op}-", dir=directory))
    try:
        package = staging / op
        shutil.copytree(export / "sources", package)
        if (package / "__init__.py").exists():
            raise ContractError("Solution sources may not define the package __init__.py")
        (package / "__init__.py").write_text(
            _PACKAGE.format(
                op=op,
                profile=profile,
                run_id=run["run_id"],
                module=module,
                symbol=symbol,
                cases=repr(cases),
                arguments=repr(identity["arguments"]),
                tensors=len(identity["input_dtypes"]),
            ),
            encoding="utf-8",
            newline="\n",
        )
        target = directory / op
        if target.exists():
            shutil.rmtree(target)
        package.rename(target)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    manifest["ops"][op] = {
        "module": op,
        "function": "call",
        "applies": "applies",
        "sha256": source_digest(directory / op),
        "verified_layouts": len(cases),
        "evidence": {
            "run_id": run["run_id"],
            "task_digest": task.identity,
            "capture_identity": generated["capture_identity"],
            "solution_digest": attempt.get("solution_digest"),
            "decision": attempt.get("decision"),
            "export_checksums": read_json(export / "checksums.json").get("manifest.json"),
        },
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    loaded = load_profile(directory)
    loaded.kernel(op)  # Import once so a broken package fails here, not in the model.
    return {"profile": profile, "op": op, "path": str(directory / op), "verified_layouts": len(cases)}
